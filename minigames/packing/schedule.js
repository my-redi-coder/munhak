/* ================= 2. 일정 · 미션 =================
   2026 정규시즌 144경기(KBO 공식 기록, 65승 5무 74패) + 경기마다 정해지는 오늘의 조건(날씨·기온·이벤트, 랜덤) */
function rng(seed) {
  var a = seed >>> 0;
  return function () {
    a |= 0; a = a + 0x6D2B79F5 | 0;
    var t = Math.imul(a ^ a >>> 15, 1 | a);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}

